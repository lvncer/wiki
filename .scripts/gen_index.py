#!/usr/bin/env python3
"""フォルダ階層を「相対Markdownリンクの索引」に変換する（Obsidianのグラフ用）。

  python3 .scripts/gen_index.py            # dry-run: 変更予定だけ表示
  python3 .scripts/gen_index.py --write    # 反映
  python3 .scripts/gen_index.py --check    # 差分があれば exit 1（CI用）
  python3 .scripts/gen_index.py --stats    # 孤立ノード数・壊れたリンクなどを表示

ルール
- 書き換えるのは <!-- index:start --> 〜 <!-- index:end --> の間だけ。手書き部分は触らない。
- READMEが無いフォルダには新規作成する。ただし「トピックの内側」だけ。
  sync_wiki_topics.py は「ファイルを直接持つ最初のフォルダ」をトピックとみなして下へ降りない。
  ファイルを持たない親フォルダにREADMEを作ると、その下のトピックが検出されなくなる。
  なのでそこには作らず、ルート README.md に見出しとして並べる。
- [[wikilink]] は出力しない。相対パスのMarkdownリンクだけ（Obsidianロックイン回避）。
- 改行コード(LF/CRLF)は既存ファイルに合わせる。標準ライブラリだけで動く。
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote, unquote

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
ROOT_TITLE = "lvncerpedia"
EXCLUDE_DIRS = {"images", "templates"}  # 索引に載せない／READMEを作らないフォルダ名
GENERIC_TITLES = {"readme", "overview", "index"}  # リンク名として情報が無い見出し
START = "<!-- index:start (auto-generated by .scripts/gen_index.py: この範囲は上書きされます) -->"
END = "<!-- index:end -->"
BLOCK_RE = re.compile(r"<!-- index:start.*?-->.*?<!-- index:end -->", re.S)


def read_text(p: Path) -> str | None:
    try:
        return p.read_bytes().decode("utf-8")
    except (UnicodeDecodeError, OSError):
        return None


def clean(t: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[\[\]]", "", t)).strip()


def title_of(p: Path) -> str:
    """最初の `# 見出し`（frontmatter・コードブロックは無視）。無ければファイル名。"""
    text = read_text(p)
    if text is None:
        return p.stem
    lines = text.splitlines()
    i = 0
    if lines and lines[0].strip() == "---":
        for j in range(1, len(lines)):
            if lines[j].strip() == "---":
                i = j + 1
                break
    fence = False
    for line in lines[i:]:
        if line.strip().startswith(("```", "~~~")):
            fence = not fence
            continue
        if not fence and line.startswith("# "):
            return clean(line[2:]) or p.stem
    return p.stem


class Wiki:
    def __init__(self, root: Path):
        self.root = root
        self._md: dict[Path, bool] = {}
        self.hubs: set[Path] = set()
        self._walk(root, False)

    def children(self, d: Path):
        dirs, files = [], []
        for p in sorted(d.iterdir(), key=lambda x: x.name.casefold()):
            if p.name.startswith("."):
                continue
            if p.is_dir():
                if p.name not in EXCLUDE_DIRS:
                    dirs.append(p)
            elif p.is_file():
                files.append(p)
        return dirs, files

    def has_md(self, d: Path) -> bool:
        if d not in self._md:
            dirs, files = self.children(d)
            self._md[d] = any(f.suffix == ".md" for f in files) or any(self.has_md(x) for x in dirs)
        return self._md[d]

    def _walk(self, d: Path, in_topic: bool) -> None:
        dirs, files = self.children(d)
        is_topic = bool(files) and d != self.root  # ルート直下のファイルはsyncスクリプトが見ない
        if d != self.root and self.has_md(d) and (in_topic or is_topic):
            self.hubs.add(d)
        for x in dirs:
            self._walk(x, in_topic or is_topic)

    def title(self, d: Path) -> str:
        readme = d / "README.md"
        if readme.exists():
            t = title_of(readme)
            if t.casefold() not in GENERIC_TITLES:  # 「README」だけの見出しはフォルダ名で代用
                return t
        return ROOT_TITLE if d == self.root else d.name

    def up(self, d: Path) -> Path:
        p = d.parent
        while p != self.root and p not in self.hubs:
            p = p.parent
        return p

    @staticmethod
    def link(frm: Path, to: Path, text: str) -> str:
        rel = os.path.relpath(to, frm).replace(os.sep, "/")
        if not rel.startswith("."):
            rel = "./" + rel
        return f"[{clean(text)}]({quote(rel, safe='/')})"

    def hub_block(self, d: Path) -> str | None:
        dirs, files = self.children(d)
        subs = [x for x in dirs if x in self.hubs]
        notes = [f for f in files if f.suffix == ".md" and f.name != "README.md"]
        if not subs and not notes:
            return None
        up = self.up(d)
        out = [START, "", f"↑ 親: {self.link(d, up / 'README.md', self.title(up))}", "",
               "## このフォルダの中身", ""]
        if subs:
            out += ["### サブトピック", ""]
            out += [f"- {self.link(d, x / 'README.md', self.title(x))}" for x in subs]
            out.append("")
        if notes:
            out += ["### ノート", ""]
            out += [f"- {self.link(d, f, title_of(f))}" for f in notes]
            out.append("")
        out.append(END)
        return "\n".join(out)

    def _tree(self, base: Path, d: Path, depth: int, out: list[str]) -> None:
        dirs, _ = self.children(d)
        for x in dirs:
            if not self.has_md(x):
                continue
            pad = "  " * depth
            if x in self.hubs:
                out.append(f"{pad}- {self.link(base, x / 'README.md', self.title(x))}")
            else:  # ファイルを持たない親フォルダ: 見出し扱い（READMEは作らない）
                out.append(f"{pad}- {x.name}")
                self._tree(base, x, depth + 1, out)

    def root_block(self) -> str:
        out = [START, "", "## 全体マップ", ""]
        dirs, _ = self.children(self.root)
        for top in dirs:
            if not self.has_md(top):
                continue
            if top in self.hubs:
                out += [f"### {self.link(self.root, top / 'README.md', self.title(top))}", ""]
            else:
                out += [f"### {top.name}", ""]
                self._tree(self.root, top, 0, out)
                out.append("")
        out.append(END)
        return "\n".join(out)


def render(existing: str | None, block: str, h1: str) -> str:
    eol = "\r\n" if existing and "\r\n" in existing else "\n"
    block = block.replace("\n", eol)
    if existing is None:
        return f"# {h1}{eol}{eol}{block}{eol}"
    if BLOCK_RE.search(existing):
        return BLOCK_RE.sub(lambda m: block, existing, count=1)
    return existing.rstrip("\r\n") + eol + eol + block + eol


def plan(root: Path):
    wiki = Wiki(root)
    changes = []  # (kind, path, new_text)
    for d in sorted(wiki.hubs | {root}):
        block = wiki.root_block() if d == root else wiki.hub_block(d)
        if block is None:
            continue
        readme = d / "README.md"
        existing = read_text(readme) if readme.exists() else None
        if readme.exists() and existing is None:
            print(f"skip (非UTF-8): {readme}", file=sys.stderr)
            continue
        new = render(existing, block, wiki.title(d))
        if new != existing:
            changes.append(("create" if existing is None else "update", readme, new))
    return changes


# ---------- stats ----------
FENCE_RE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1[^\n]*$", re.S | re.M)
INLINE_RE = re.compile(r"`[^`\n]*`")
LINK_RE = re.compile(r"(?<!!)\[[^\]]*\]\(\s*<?([^)>\s]+)>?(?:\s+\"[^\"]*\")?\s*\)")
WIKI_RE = re.compile(r"\[\[([^\]]+)\]\]")
SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]*:")


def stats(root: Path) -> None:
    notes: list[Path] = []
    for dp, dn, fn in os.walk(root):
        dn[:] = [x for x in dn if not x.startswith(".") and x not in EXCLUDE_DIRS]
        notes += [Path(dp) / f for f in fn if f.endswith(".md")]
    ids = {p.resolve() for p in notes}
    linked: set[Path] = set()
    edges = broken = dir_links = 0
    wiki_files: dict[str, int] = {}
    for p in notes:
        body = INLINE_RE.sub("", FENCE_RE.sub("", read_text(p) or ""))
        me = p.resolve()
        for m in LINK_RE.finditer(body):
            raw = m.group(1)
            if SCHEME_RE.match(raw) or raw.startswith(("#", "//")):
                continue
            rel = unquote(raw.split("#", 1)[0].split("?", 1)[0])
            if not rel:
                continue
            tgt = (p.parent / rel).resolve()
            if tgt in ids and tgt != me:
                edges += 1
                linked |= {me, tgt}
            elif rel.endswith(".md") and tgt not in ids:
                broken += 1
            elif tgt.is_dir():
                dir_links += 1
        n = len(WIKI_RE.findall(body))
        if n:
            wiki_files[str(p.relative_to(root))] = n
    total = len(ids)
    orphans = total - len(linked)
    print(f"ノート数            : {total}")
    print(f"リンク(線)の数      : {edges}")
    print(f"孤立ノード          : {orphans} ({orphans * 100 // max(total, 1)}%)")
    print(f"壊れた .md リンク   : {broken}")
    print(f"フォルダ宛リンク    : {dir_links}  ← Obsidianのグラフには線が出ない")
    print(f"[[wikilink]]        : {sum(wiki_files.values())} 件 / {len(wiki_files)} ファイル")
    for f, n in list(wiki_files.items())[:5]:
        print(f"    {f} ({n})")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    ap.add_argument("--write", action="store_true", help="変更を書き込む（省略時はdry-run）")
    ap.add_argument("--check", action="store_true", help="差分があれば exit 1")
    ap.add_argument("--stats", action="store_true", help="リンク統計だけ表示")
    a = ap.parse_args()
    root = a.root.resolve()
    if a.stats:
        stats(root)
        return 0
    changes = plan(root)
    creates = [c for c in changes if c[0] == "create"]
    updates = [c for c in changes if c[0] == "update"]
    print(f"新規作成 {len(creates)} / 更新 {len(updates)} / 変更なし（それ以外）")
    if not a.write:
        for kind, path, _ in changes[:12]:
            print(f"  {kind:6} {path.relative_to(root)}")
        if len(changes) > 12:
            print(f"  ... 他 {len(changes) - 12} 件")
        return 1 if (a.check and changes) else 0
    for _, path, text in changes:
        path.write_bytes(text.encode("utf-8"))
    print("書き込み完了")
    return 0


if __name__ == "__main__":
    sys.exit(main())
